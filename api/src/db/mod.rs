pub mod users;

pub use sqlx::postgres::{PgPool, PgPoolOptions};

pub async fn make_pool(database_url: &str) -> Result<PgPool, sqlx::Error> {
    PgPoolOptions::new()
        .max_connections(10)
        .acquire_timeout(std::time::Duration::from_secs(5))
        .connect(database_url)
        .await
}
